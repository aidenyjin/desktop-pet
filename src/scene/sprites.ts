/**
 * One-bit sprites as text. `#` is ink, `.` is transparent. Keep rows the
 * same length; `sprite()` validates that at startup so a stray character in
 * a drawing fails loudly instead of rendering as a smudge.
 */

export interface Sprite {
  w: number;
  h: number;
  rows: string[];
}

function sprite(rows: string[]): Sprite {
  const w = rows[0]?.length ?? 0;
  for (const r of rows) {
    if (r.length !== w) throw new Error(`sprite row width mismatch: ${r.length} vs ${w}\n${rows.join("\n")}`);
  }
  return { w, h: rows.length, rows };
}

